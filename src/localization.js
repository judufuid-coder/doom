const ARABIC_PHRASES = [...ARABIC_TEXT]
  .filter(([source]) => source.length >= 16)
  .sort(([left], [right]) => right.length - left.length);

function translateText(value, language = 'en') {
  if (language !== 'ar' || typeof value !== 'string') return value;
  const exact = ARABIC_TEXT.get(value);
  if (exact) return exact;
  if (value.includes('\n')) {
    return value.split('\n').map(line => translateText(line, language)).join('\n');
  }
  for (const [source, target] of ARABIC_PHRASES) {
    if (value.includes(source)) value = value.replaceAll(source, target);
  }
  for (const [pattern, replacement] of ARABIC_PATTERNS) {
    if (pattern.test(value)) {
      return value.replace(pattern, replacement);
    }
  }
  return value;
}

function localizePayload(value, language = 'en', key = '', ancestors = new WeakSet()) {
  if (language !== 'ar' || value == null) return value;
  if (typeof value === 'string') return translateText(value, language);
  if (typeof value !== 'object') return value;
  if (value instanceof MessagePayload) {
    value.options = localizePayload(value.options, language, 'options', ancestors);
    return value;
  }

  if (ancestors.has(value)) return undefined;
  ancestors.add(value);
  if (Array.isArray(value)) {
    const localized = [];
    try {
      for (const item of value) localized.push(localizePayload(item, language, '', ancestors));
    } finally {
      ancestors.delete(value);
    }
    return localized;
  }

  let source;
  const ancestorsToRemove = [value];
  try {
    source = typeof value.toJSON === 'function' && /Builder$/.test(value.constructor?.name || '')
      ? value.toJSON()
      : value;
    if (source !== value && source && typeof source === 'object') {
      if (ancestors.has(source)) return undefined;
      ancestors.add(source);
      ancestorsToRemove.push(source);
    }
    const localized = {};
    for (const [property, child] of Object.entries(source)) {
      if (property === 'files' || property === 'attachment' || property === 'reply') {
        localized[property] = child;
      } else {
        localized[property] = localizePayload(child, language, property, ancestors);
      }
    }
    return localized;
  } finally {
    for (const ancestor of ancestorsToRemove) ancestors.delete(ancestor);
  }
}

function localizeCommandDefinition(command) {
  const localize = option => {
    if (option.description) {
      option.description_localizations = {
        ...option.description_localizations,
        ar: translateText(option.description, 'ar')
      };
    }
    if (option.choices) {
      for (const choice of option.choices) {
        choice.name_localizations = {
          ...choice.name_localizations,
          ar: translateText(choice.name, 'ar')
        };
      }
    }
    if (option.options) option.options.forEach(localize);
  };
  if (command.description) {
    command.description_localizations = {
      ...command.description_localizations,
      ar: translateText(command.description, 'ar')
    };
  }
  command.options?.forEach(localize);
  return command;
}

